#!/bin/zsh
# Builds "Album Importer.app" from the Swift package: release binary, Info.plist,
# icon and an ad-hoc signature.
#
# Usage: scripts/build-app.sh [output-dir]   (default: build/)
set -euo pipefail

cd "$(dirname "$0")/.."
out="${1:-build}"
app="$out/Album Importer.app"

swift build -c release --product AlbumImporter
swift build -c release --product albumctl
bin="$(swift build -c release --show-bin-path)"

rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$bin/AlbumImporter" "$app/Contents/MacOS/AlbumImporter"
# The same engine from the command line: "Album Importer.app/Contents/MacOS/albumctl".
cp "$bin/albumctl" "$app/Contents/MacOS/albumctl"
# Generated by scripts/make-icon.swift.
cp assets/AppIcon.icns "$app/Contents/Resources/AppIcon.icns"

cat > "$app/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Album Importer</string>
    <key>CFBundleDisplayName</key><string>Album Importer</string>
    <key>CFBundleIdentifier</key><string>app.albumimporter.AlbumImporter</string>
    <key>CFBundleExecutable</key><string>AlbumImporter</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.1</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>LSMinimumSystemVersion</key><string>26.0</string>
    <key>LSApplicationCategoryType</key><string>public.app-category.photography</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSPrincipalClass</key><string>NSApplication</string>
    <key>NSRemovableVolumesUsageDescription</key>
    <string>Album Importer reads photo folders from your external drives and copies them into Albums &amp; Trips.</string>
    <key>NSDocumentsFolderUsageDescription</key>
    <string>Album Importer writes its run logs, timeline sheet and history files to your records folder in Documents.</string>
</dict>
</plist>
PLIST

codesign --force --sign - "$app/Contents/MacOS/albumctl"
codesign --force --sign - "$app"
echo "Built $app"
